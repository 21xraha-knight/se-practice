def main():
    parser = argparse.ArgumentParser(description="Structural checker for SIS #02")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    args = parser.parse_args()

    if not os.path.isdir("tests") and not os.path.exists(REPORT):
        msg = "run this from inside your sis-02/ folder:  cd sis-02 && python tests/check_sis.py"
        print(json.dumps({"ok": False, "error": msg}) if args.json else "ERROR: " + msg)
        return 3

    if not os.path.exists(REPORT):
        res, measured, code = all_error(f"{REPORT} not found"), {}, 2
    else:
        res, measured = check(read(REPORT))
        c = res.counts()
        code = 0 if c["FAIL"] == 0 and c["ERROR"] == 0 else 1

    c = res.counts()
    if args.json:
        print(json.dumps({"ok": code == 0, "counts": c, "total": sum(c.values()),
                          "rows": res.rows, "measured": measured}, ensure_ascii=False, indent=2))
    else:
        print_human(res, REPORT)
    return code


