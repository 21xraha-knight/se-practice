def check_tables(res, measured, s):
    # T1 traceability
    if s.get(5) is None:
        res.add("T1", "ERROR", "section 5 is missing")
    else:
        rows = table(s[5]) or []
        covered, probs = set(), []
        for r in rows:
            if len(r) < 3:
                continue
            rule = re.findall(r"\bR([1-5])\b", r[0])
            if not rule or PLACEHOLDER.search(" ".join(r)):
                continue
            row = f"R{rule[0]}"
            if not re.search(r"\bAC-0[1-6]\b", r[0]):
                probs.append(f"{row} row names no AC-ID")
            elif not filled(r[1], 3):
                probs.append(f"{row} row has no model evidence")
            elif not filled(r[2], 1):
                probs.append(f"{row} row has no T-ID or extra check")
            else:
                covered |= {f"R{x}" for x in rule}
        missing = [r for r in RULES if r not in covered]
        res.add("T1", "FAIL" if missing or probs else "PASS",
                "; ".join(probs + ([f"no complete row for {', '.join(missing)}"] if missing else []))
                if missing or probs else "R1-R5 each traced to a criterion, model evidence and a case")

    # T2 walkthroughs
    walk = {c: None for c in CASES}
    if s.get(6) is None:
        res.add("T2", "ERROR", "section 6 is missing")
    else:
        rows = table(s[6]) or []
        probs = []
        for case in CASES:
            r = next((r for r in rows if r and re.match(rf"^\**{case}\b", r[0])), None)
            if r is None or len(r) < 3:
                probs.append(f"{case} row missing")
                continue
            verdict = re.match(r"^\W*(pass|fail)\b(.*)$", r[2], re.I)
            if verdict:
                walk[case] = verdict.group(1).lower()     # declared in submission.yml, even if T2 FAILs
            if not filled(r[1], 10):
                probs.append(f"{case} path empty or under 10 words")
            elif not verdict:
                probs.append(f"{case} judgment does not start with Pass or Fail")
            elif len(words(verdict.group(2))) < 3:
                probs.append(f"{case} gives a verdict with no location")
        measured["walkthroughs"] = walk
        res.add("T2", "FAIL" if probs else "PASS",
                "; ".join(probs) if probs else
                "T1-T4: " + ", ".join(f"{c} {v}" for c, v in walk.items()))

    # T3 review decisions
    if s.get(7) is None:
        res.add("T3", "ERROR", "section 7 is missing")
    else:
        rows = table(s[7]) or []
        good, probs = 0, []
        for i, r in enumerate(rows, 1):
            if len(r) < 4 or not any(filled(c) for c in r[:4]):
                continue
            if not all(filled(c) for c in r[:4]):
                probs.append(f"row {i}: a cell is empty")
            elif not re.search(r"\bR[1-5]\b", r[3]):
                probs.append(f"row {i}: rule is not one of R1-R5")
            elif len(words(r[2])) < 8:
                probs.append(f"row {i}: reason under 8 words")
            else:
                good += 1
        measured["review_decisions"] = good
        res.add("T3", "PASS" if good >= 3 else "FAIL",
                f"{good} complete review decision(s), 3 required" + (" — " + "; ".join(probs) if probs else ""))

    # T4 source checks, R1 references
    body = s.get(13)
    checks = table(body, "Source checks") if body is not None else None
    if checks is None:
        res.add("T4", "ERROR", "section 13 or its ### Source checks heading is missing")
    else:
        complete = [r for r in checks if len(r) >= 4 and all(filled(c) for c in r[:4])]
        measured["source_checks"] = len(complete)
        probs = []
        for i, r in enumerate(complete, 1):
            if not LOCATOR.search(r[1]):
                probs.append(f"row {i} has no slide / page / section / chapter / figure / URL")
            elif URL.search(r[1]) and not ACCESS_DATE.search(r[1]):
                probs.append(f"row {i} gives a URL with no access date")
        if len(complete) < 2:
            probs.insert(0, f"{len(complete)} complete row(s), 2 required")
        res.add("T4", "FAIL" if probs else "PASS",
                "; ".join(probs) if probs else f"{len(complete)} source checks, every one with a locator")
    if body is None:
        res.add("R1", "ERROR", "section 13 is missing")
    else:
        part = re.split(r"^###\s+Source checks", body, flags=re.M | re.I)[0]
        refs = [l.strip()[2:] for l in part.splitlines() if l.strip().startswith(("- ", "* "))]
        refs = [r for r in refs if r and not PLACEHOLDER.search(r) and len(words(r)) >= 4]
        probs = [] if refs else ["no reference entries (one per line, starting with '- ')"]
        for u in URL.findall(" ".join(r[1] for r in (checks or []) if len(r) > 1)):
            if u.lower().rstrip(".,;") not in part.lower():
                probs.append(f"{u} is in the source checks but not in References")
        res.add("R1", "FAIL" if probs else "PASS",
                "; ".join(probs) if probs else f"{len(refs)} reference(s); every table URL listed")


def check_exchanges(res, measured, s, originals):
    ids = ("E1", "E2", "E3", "E4", "E5", "E6", "E7", "E8", "E9", "E10")
