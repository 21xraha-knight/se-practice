def check_requirements(res, measured, body):
    if body is None:
        for cid in ("Q1", "Q2", "Q3", "Q4", "Q5"):
            res.add(cid, "ERROR", "section 2 is missing")
        return
    stories = split_sub(body, r"US-\d+")

    # Q1 — three stories, each with its statement
    good, probs = [], []
    for sid in STORIES:
        text = label_value(stories.get(sid, ""), sid)
        if sid not in stories:
            probs.append(f"{sid} heading missing")
        elif not text or PLACEHOLDER.search(text) or len(words(text)) < 8:
            probs.append(f"{sid} statement empty or under 8 words")
        else:
            good.append(sid)
    measured["stories"] = len(good)
    res.add("Q1", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else "US-01, US-02 and US-03 written")

    # The criteria: one bullet each, `- **AC-0N** (Rn): Given … When … Then …`
    found = {}            # AC id -> (story, text)
    for sid, block in stories.items():
        current, buf = None, []
        for line in block.splitlines() + [""]:
            m = re.match(r"^\s*[-*]\s+\**\s*(AC-\d+)", line)
            if m or not line.strip():
                if current:
                    found.setdefault(current, (sid, " ".join(buf)))
                current, buf = (m.group(1).upper(), [line]) if m else (None, [])
            elif current:
                buf.append(line)

    gwt_ok, probs = [], []
    for cid in CRITERIA:
        if cid not in found:
            probs.append(f"{cid} missing")
            continue
        text = found[cid][1]
        if PLACEHOLDER.search(text):
            probs.append(f"{cid} not filled")
            continue
        lost = [w for w in ("Given", "When", "Then") if not re.search(rf"\b{w}\b", text, re.I)]
        if lost:
            probs.append(f"{cid} has no {'/'.join(lost)}")
        else:
            gwt_ok.append(cid)
    measured["criteria"] = len(gwt_ok)
    res.add("Q2", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else "AC-01 to AC-06 each have Given, When and Then")

    per_story = {sid: sorted(c for c, (s, _) in found.items() if s == sid) for sid in STORIES}
    bad = [f"{sid} has {len(per_story[sid])}" for sid in STORIES if len(per_story[sid]) != 2]
    res.add("Q3", "FAIL" if bad else "PASS",
            "two criteria per story required — " + ", ".join(bad) if bad
            else "two criteria under each story")

    unmapped, covered = [], set()
    for cid in CRITERIA:
        if cid not in found:
            continue
        ids = set(re.findall(r"\bR(\d+)\b", found[cid][1]))
        valid = {f"R{n}" for n in ids if f"R{n}" in RULES}
        if not valid or len(valid) != len(ids):
            unmapped.append(cid)
        covered |= valid
    uncovered = [r for r in RULES if r not in covered]
    probs = ([f"{', '.join(unmapped)} name(s) no rule, or a rule outside R1-R5"] if unmapped else []) \
        + ([f"no criterion maps to {', '.join(uncovered)}"] if uncovered else [])
    res.add("Q4", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else "every criterion names its rules; R1-R5 all covered")

    text = norm(body)
    hits = [name for name, pattern in EXCLUDED if re.search(pattern, text, re.I)]
    res.add("Q5", "FAIL" if hits else "PASS",
            "section 2 mentions excluded feature(s): " + ", ".join(hits)
            + " — remove them; say they are out of scope in section 1" if hits
            else "none of the five excluded features in the stories or criteria")


def check_sequence(res, src, path_note):
    ids = ("SQ1", "SQ2", "SQ3", "SQ4", "SQ5", "SQ6", "SQ7", "SQ8")
    if src is None or not is_puml(src):
        why = path_note or ("models/sequence.puml not found" if src is None
                            else "models/sequence.puml has no @startuml / @enduml")
        for cid in ids:
            res.add(cid, "ERROR", why)
        return None
    sq = parse_sequence(src)
    events, branches = sq["events"], sq["branches"]
    messages = [e for e in events if e["kind"] == "message"]
    declared = {key(k) for k in sq["participants"]}

    # SQ1
    probs = []
    if len({v for v in sq["participants"].values()}) < 3:
        probs.append("fewer than 3 participants declared")
    undeclared = sorted({e for m in messages for e in (m["frm"], m["to"])
                         if e and e not in "[]" and key(e) not in declared})
    if undeclared:
        probs.append("used but never declared: " + ", ".join(undeclared))
    unlabeled = [m for m in messages if not m["label"]]
    if unlabeled:
        probs.append(f"{len(unlabeled)} message(s) without a name")
    if not messages:
        probs.append("no messages")
    res.add("SQ1", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else
            f"{len(set(sq['participants'].values()))} participants declared, {len(messages)} messages, all named")

    creates = [e for e in events if e["kind"] == "create" or
               (e["kind"] == "message" and CREATE.search(e["label"]))]
    first_create = creates[0]["line"] if creates else None

    # SQ2
    catalog = next((m for m in messages if CATALOG.search(m["label"])), None)
    request = next((m for m in messages if catalog and m["line"] > catalog["line"]
                    and REQUEST.search(m["label"]) and not CREATE.search(m["label"])), None)
    if catalog is None:
        res.add("SQ2", "FAIL", "no catalog browsing — a message naming the catalog or the offerings (R1)")
    elif request is None:
        res.add("SQ2", "FAIL", "no registration request after the catalog — a message naming register / enrol")
    else:
        res.add("SQ2", "PASS", f"catalog \"{catalog['label'][:40]}\" then request \"{request['label'][:40]}\"")

    # SQ3
    alts = [b for b in branches if b["kind"] in ("alt", "alt-else")]
    unguarded = [b for b in alts if not b["guard"].strip("[] ")]
    kinds = [rejection_kind(b["guard"]) for b in alts]
    success = [b for b, k in zip(alts, kinds) if k is None and b["guard"].strip("[] ")]
    probs = []
    if len(alts) < 3:
        probs.append(f"{len(alts)} alt branch(es); success, full and duplicate need 3")
    if unguarded:
        probs.append(f"{len(unguarded)} alt/else branch(es) with no [guard]")
    if "full" not in kinds:
        probs.append("no branch guarded as full (e.g. [course full])")
    if "duplicate" not in kinds:
        probs.append("no branch guarded as duplicate (e.g. [already enrolled])")
    if not success:
        probs.append("no guarded success branch")
    res.add("SQ3", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else
            f"{len(alts)} guarded alt branches: success, full and duplicate")

    # SQ4
    if first_create is None:
        res.add("SQ4", "FAIL", "no message creates the Enrollment (create / insert / save)")
    elif request is None:
        res.add("SQ4", "FAIL", "no registration request to check after (see SQ2)")
    else:
        window = [e for e in events if request["line"] < e["line"] <= first_create]
        def seen(pattern):
            return any(pattern.search(e["label"] or "") for e in window)
        missing = [n for n, p in (("duplicate", DUP_CHECK), ("capacity", CAPACITY_CHECK)) if not seen(p)]
        res.add("SQ4", "FAIL" if missing else "PASS",
                "no " + " or ".join(missing) + " check between the registration request and the "
                "creation of the Enrollment (R2, R3 — the catalog view does not count)" if missing
                else "duplicate and capacity checked after the request, before creation")

    # SQ5
    confirms = [m for m in messages if CONFIRM.search(m["label"])]
    if not confirms:
        res.add("SQ5", "FAIL", "no confirmation message (R4) — name it with the word confirm")
    elif first_create is None:
        res.add("SQ5", "FAIL", "a confirmation, but nothing is created before it")
    else:
        early = [m for m in confirms if m["line"] < first_create]
        res.add("SQ5", "FAIL" if early else "PASS",
                f"confirmation \"{early[0]['label'][:40]}\" comes before the Enrollment is created (R4)"
                if early else "confirmation follows creation")

    # SQ6, SQ7
    rejecting = {}
    for i, b in enumerate(branches):
        kind = rejection_kind(b["guard"]) if b["kind"].startswith("alt") else None
        if kind:
            rejecting[i] = kind
    leaks, returned = [], {"full": False, "duplicate": False}
    for e in events:
        inside = [rejecting[i] for i in e["enclosing"] if i in rejecting]
        if not inside or e["kind"] not in ("message", "create"):
            continue
        label = e["label"] or ""
        if e["kind"] == "create" or CREATE.search(label) or STATE.search(label) or CONFIRM.search(label):
            leaks.append(label[:40])
        reason = inside[-1]
        if reason == "full" and re.search(r"\bfull\b", label, re.I):
            returned["full"] = True
        if reason == "duplicate" and (DUP.search(label) or re.search(r"enrolled", label, re.I)):
            returned["duplicate"] = True
    if not rejecting:
        res.add("SQ6", "FAIL", "no rejection branch to inspect (see SQ3)")
        res.add("SQ7", "FAIL", "no rejection branch to inspect (see SQ3)")
    else:
        res.add("SQ6", "FAIL" if leaks else "PASS",
                "a rejection branch creates, updates or confirms: " + "; ".join(leaks) if leaks
                else "rejection branches create, update and confirm nothing (R5)")
        kinds_present = set(rejecting.values())
        missing = [k for k in ("full", "duplicate") if k not in kinds_present or not returned[k]]
        res.add("SQ7", "FAIL" if missing else "PASS",
                "no message returns the reason on the " + " / ".join(missing)
                + " branch — R5 says explain \"course full\" or \"already enrolled\"" if missing
                else "each rejection branch returns its reason")

    # SQ8
    texts = [e["label"] for e in events if e["kind"] in ("note", "branch")]
    critical = any(b["kind"] == "critical" for b in branches)
    ok = critical or any(ATOMIC.search(t or "") for t in texts)
    res.add("SQ8", "PASS" if ok else "FAIL",
            "the atomic operation is stated" if ok
            else "no note or group states that the final checks and creation are one atomic operation")
    return sq


def check_classes(res, src, path_note):
    ids = ("CL1", "CL2", "CL3", "CL4", "CL5", "CL6")
    if src is None or not is_puml(src):
        why = path_note or ("models/classes.puml not found" if src is None
                            else "models/classes.puml has no @startuml / @enduml")
        for cid in ids:
            res.add(cid, "ERROR", why)
        return None
    cl = parse_classes(src)
    cmap = {key(k): k for k in cl["classes"]}

    missing = [c for c in REQUIRED_CLASSES if key(c) not in cmap]
    res.add("CL1", "FAIL" if missing else "PASS",
            "missing class(es): " + ", ".join(missing) + " — these four names are required, spelled this way"
            if missing else "Student, Course, CourseOffering and Enrollment present")

    def members(name):
        return [key(x) for x in cl["classes"].get(cmap.get(key(name), ""), [])]

    probs = []
    if not any("code" in m for m in members("Course")):
        probs.append("Course has no code (R1)")
    if not any("title" in m or "name" in m for m in members("Course")):
        probs.append("Course has no title (R1)")
    if not any("semester" in m or "term" in m for m in members("CourseOffering")):
        probs.append("CourseOffering has no semester (R1)")
    if not any("capacity" in m for m in members("CourseOffering")):
        probs.append("CourseOffering has no capacity (R2)")
    if not any("id" in m or "number" in m for m in members("Student")):
        probs.append("Student has no identifier")
    res.add("CL2", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else "code, title, semester, capacity and a student identifier present")

    assoc = associations(cl)
    no_mult = [f"{r['left']}-{r['right']}" for r in assoc if not r["lm"] or not r["rm"]]
    if not assoc:
        res.add("CL3", "FAIL", "no associations")
    else:
        res.add("CL3", "FAIL" if no_mult else "PASS",
                "association(s) without a multiplicity at both ends: " + ", ".join(no_mult) if no_mult
                else f"{len(assoc)} associations, multiplicities at both ends")

    def between(a, b):
        return [r for r in assoc if {key(r["left"]), key(r["right"])} == {key(a), key(b)}]

    probs = []
    for owner, part in (("Student", "Enrollment"), ("CourseOffering", "Enrollment"), ("Course", "CourseOffering")):
        rels = between(owner, part)
        if not rels:
            probs.append(f"no association {owner}-{part}")
            continue
        r = rels[0]
        owner_m, part_m = (r["lm"], r["rm"]) if key(r["left"]) == key(owner) else (r["rm"], r["lm"])
        if owner_m.replace(" ", "") != "1":
            probs.append(f"{owner} end of {owner}-{part} is {owner_m or 'empty'!s}, expected 1")
        if part != "CourseOffering" and not MANY.match(part_m.replace(" ", "")):
            probs.append(f"{part} end of {owner}-{part} is {part_m or 'empty'!s}, expected 0..* or *")
        if part == "CourseOffering" and not re.match(r"^(\*|[01]\.\.(\*|n))$", part_m.replace(" ", "")):
            probs.append(f"CourseOffering end of Course-CourseOffering is {part_m or 'empty'!s}, expected 0..* or 1..*")
    res.add("CL4", "FAIL" if probs else "PASS",
            "; ".join(probs) if probs else
            "1 Student and 1 CourseOffering per Enrollment, 0..* each way; 1 Course per CourseOffering")

    notes = norm(" ".join(cl["notes"]))
    braces = norm(" ".join(re.findall(r"\{[^}]*\}", " ".join(" ".join(v) for v in cl["classes"].values()))))
    text = notes + " " + braces
    cap = re.search(r"capacity", text)
    uniq = re.search(r"unique|at most one|duplicate|one enrol", text)
    probs = [x for x, ok in (("capacity", cap), ("uniqueness", uniq)) if not ok]
    res.add("CL5", "FAIL" if probs else "PASS",
            "no note states the " + " or the ".join(probs) + " constraint — multiplicity alone cannot express it"
            if probs else "capacity and uniqueness constraints stated in notes")

    extra = [c for c in cl["classes"] if key(c) not in {key(x) for x in REQUIRED_CLASSES}]
    unjust = [c for c in extra if not justified(cl["raw"], cl["declared_at"].get(c, 0))]
    res.add("CL6", "FAIL" if unjust else "PASS",
            "extra class(es) without a ' why: comment on the line above: " + ", ".join(sorted(unjust))
            if unjust else (f"{len(extra)} extra class(es), each with a ' why:" if extra else "no extra classes"))
    return cl


