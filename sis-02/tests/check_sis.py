def parse_classes(src):
    lines, raw = puml_lines(src)
    classes, declared_at, aliases, relations, notes, note_aliases = {}, {}, {}, [], [], set()
    current = None
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        idx = i
        i += 1
        if not s:
            continue
        if current is not None:
            if s.startswith("}"):
                current = None
            else:
                classes[current].append(s)
            continue
        m = re.match(r'^note\b(.*)$', s, re.I)
        if m:
            rest = m.group(1)
            q = re.match(r'^\s*"([^"]*)"\s*(?:as\s+(\w+))?', rest)
            if q:
                notes.append(q.group(1))
                if q.group(2):
                    note_aliases.add(q.group(2))
            elif ":" in rest:
                notes.append(rest.split(":", 1)[1])
            else:
                a = re.search(r'\bas\s+(\w+)\s*$', rest)
                if a:
                    note_aliases.add(a.group(1))
                buf = []
                while i < len(lines) and not re.match(r'^\s*end\s*note', lines[i], re.I):
                    buf.append(lines[i])
                    i += 1
                i += 1
                notes.append(" ".join(buf))
            continue
        m = CLASS_DECL.match(s)
        if m:
            name = m.group(1) or m.group(2)
            classes.setdefault(name, [])
            declared_at.setdefault(name, idx)
            if m.group(3):
                aliases[m.group(3)] = name
            if m.group(4) and not m.group(5):
                current = name
            continue
        m = RELATION.match(s)
        if m and ("-" in m.group(3) or "." in m.group(3)):
            left = aliases.get(m.group(1).strip('"'), m.group(1).strip('"'))
            right = aliases.get(m.group(5).strip('"'), m.group(5).strip('"'))
            if left in note_aliases or right in note_aliases:
                continue
            relations.append({"left": left, "lm": (m.group(2) or "").strip(), "arrow": m.group(3),
                              "rm": (m.group(4) or "").strip(), "right": right,
                              "label": m.group(6) or "", "line": idx})
            for name in (left, right):
                classes.setdefault(name, [])
                declared_at.setdefault(name, idx)
            continue
        m = re.match(r'^([\w.]+)\s*:\s*(.+)$', s)          # Class : attribute
        if m and m.group(1) in classes:
            classes[m.group(1)].append(m.group(2))
    return {"classes": classes, "declared_at": declared_at, "relations": relations,
            "notes": notes, "raw": raw}


def associations(cl):
    """Plain associations: solid lines, not inheritance or realization."""
    return [r for r in cl["relations"] if "|" not in r["arrow"] and "^" not in r["arrow"]
            and "." not in r["arrow"]]


