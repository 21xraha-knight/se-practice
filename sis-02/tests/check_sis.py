def words(text):
    """Words as a reader counts them: tokens with at least one letter or digit."""
    text = COMMENT.sub(" ", text or "")
    text = re.sub(r"[*_`#>|]", " ", text)
    return [t for t in text.split() if re.search(r"[0-9A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]", t)]


def norm(text):
    text = (text or "").lower()
    text = re.sub(r"[‐-―−]", "-", text)          # every dash is a hyphen
    text = re.sub(r"[‘’“”]", "'", text)
    return re.sub(r"\s+", " ", text).strip()


def key(text):
    """Lowercase, letters and digits only — how names are compared across files."""
    return re.sub(r"[^a-z0-9]", "", (text or "").lower())


def content_words(text):
    return {w for w in re.findall(r"[a-zA-Zа-яА-Я]{5,}", (text or "").lower()) if w not in STOPWORDS}


def shingles(text, n=5):
    toks = re.findall(r"\w+", (text or "").lower())
    return {" ".join(toks[i:i + n]) for i in range(max(0, len(toks) - n + 1))}


def share(part, whole_text):
    """What fraction of `part`'s shingles also occur in `whole_text`."""
    if not part:
        return 0.0
    return len(part & shingles(whole_text)) / len(part)


