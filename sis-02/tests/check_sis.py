def puml_lines(src):
    """(lines, raw): comments blanked out, line numbers kept, so raw[i] can be inspected."""
    raw = (src or "").splitlines()
    out, in_block = [], False
    for line in raw:
        s = line
        if in_block:
            if "'/" in s:
                s, in_block = s.split("'/", 1)[1], False
            else:
                out.append("")
                continue
        if "/'" in s:
            before, after = s.split("/'", 1)
            if "'/" in after:
                s = before + after.split("'/", 1)[1]
            else:
                s, in_block = before, True
        if s.strip().startswith("'"):
            s = ""
        out.append(s)
    return out, raw


def is_puml(src):
    lines = [l.strip() for l in puml_lines(src)[0]]
    return any(l.startswith("@startuml") for l in lines) and any(l.startswith("@enduml") for l in lines)


def justified(raw, idx):
    """True if the nearest non-empty line above idx is a comment containing 'why:'."""
    j = idx - 1
    while j >= 0 and not raw[j].strip():
        j -= 1
    return j >= 0 and raw[j].strip().startswith("'") and "why:" in raw[j].lower()


