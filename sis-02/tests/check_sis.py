def split_sections(text):
    """{number: body} for every `## N.` heading outside a code block, comments removed."""
    text = COMMENT.sub("", text)
    found, order, current, buf, in_fence = {}, [], None, [], None
    for line in text.splitlines():
        fence = FENCE.match(line.strip())
        if fence:
            mark = fence.group(1)
            if in_fence is None:
                in_fence = mark
            elif mark[0] == in_fence[0] and len(mark) >= len(in_fence) and line.strip() == mark:
                in_fence = None
        m = HEADING.match(line) if in_fence is None else None
        if m:
            if current is not None:
                found[current] = "\n".join(buf)
            current, buf = int(m.group(1)), []
            order.append(current)
            continue
        if current is not None:
            buf.append(line)
    if current is not None:
        found[current] = "\n".join(buf)
    return found, order


def label_value(body, label):
    m = re.search(rf"\*\*{re.escape(label)}:?\*\*:?\s*(.*)", body or "")
    return m.group(1).strip() if m else None


def fenced_after(body, label):
    """The first fenced block after a line containing **label:**."""
    lines = (body or "").splitlines()
    start = None
    for i, line in enumerate(lines):
        if f"**{label}:**" in line:
            start = i + 1
            break
    if start is None:
        return None
    for i in range(start, len(lines)):
        stripped = lines[i].strip()
        if not stripped:
            continue
        opening = FENCE.match(stripped)
        if not opening:
            return None
        mark = opening.group(1)
        out = []
        for j in range(i + 1, len(lines)):
            s = lines[j].strip()
            if s and s[0] == mark[0] and set(s) == {mark[0]} and len(s) >= len(mark):
                return "\n".join(out)
            out.append(lines[j])
        return "\n".join(out)
    return None


def split_sub(body, pattern):
    """{ID: text} for `### <ID> …` sub-headings outside code blocks."""
    parts, current, buf, in_fence = {}, None, [], None
    for line in (body or "").splitlines():
        fence = FENCE.match(line.strip())
        if fence:
            mark = fence.group(1)
            if in_fence is None:
                in_fence = mark
            elif mark[0] == in_fence[0] and line.strip() == mark:
                in_fence = None
        m = re.match(rf"^###\s+({pattern})\b", line) if in_fence is None else None
        if m:
            if current:
                parts[current] = "\n".join(buf)
            current, buf = m.group(1).upper(), []
            continue
        if current:
            buf.append(line)
    if current:
        parts[current] = "\n".join(buf)
    return parts


def meta(block, name):
    m = re.search(rf"^\s*[-*]?\s*\*\*{name}:\*\*\s*(.*)$", block, re.MULTILINE)
    return m.group(1).strip() if m else ""


def table(body, heading=None):
    """Data rows of the first markdown table in `body` (after `### heading`, if given)."""
    lines = (body or "").splitlines()
    start = 0
    if heading:
        start = None
        for i, line in enumerate(lines):
            if re.match(rf"^###\s+{heading}\b", line, re.IGNORECASE):
                start = i + 1
                break
        if start is None:
            return None
    rows, seen = [], False
    for line in lines[start:]:
        s = line.strip()
        if heading and s.startswith("###"):
            break
        if not s.startswith("|"):
            if seen and s:
                break
            continue
        seen = True
        cells = [c.strip() for c in s.strip("|").split("|")]
        if all(re.fullmatch(r":?-{3,}:?", c) for c in cells if c):
            continue
        rows.append(cells)
    return rows[1:] if rows else []


